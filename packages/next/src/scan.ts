import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

export interface ScannedRoute {
  path: string;
  page: boolean;
  /** Absolute path of the route's agent.* file, when it has one. */
  agentFile?: string;
}

const PAGE_FILE = /^page\.(tsx|ts|jsx|js|mdx)$/;
const AGENT_FILE = /^agent\.(tsx|ts|jsx|js)$/;

/** Folders that are not URL segments the agent can stand in (MVP scope). */
function skippedFolder(name: string): boolean {
  return (
    name === 'node_modules' ||
    name.startsWith('_') ||
    name.startsWith('@') ||
    name.startsWith('(.') ||
    name.startsWith('[...') ||
    name.startsWith('[[...')
  );
}

const isRouteGroup = (name: string) => name.startsWith('(') && name.endsWith(')');

export function findAppDir(projectRoot: string): string | undefined {
  return [path.join(projectRoot, 'app'), path.join(projectRoot, 'src', 'app')].find((candidate) =>
    existsSync(candidate)
  );
}

export function scanAppDir(appDir: string): ScannedRoute[] {
  const routes = new Map<string, ScannedRoute>();

  const walk = (dir: string, urlSegments: string[]) => {
    const entries = readdirSync(dir, { withFileTypes: true });
    const page = entries.some((entry) => entry.isFile() && PAGE_FILE.test(entry.name));
    const agent = entries.find((entry) => entry.isFile() && AGENT_FILE.test(entry.name));
    if (page || agent) {
      const urlPath = `/${urlSegments.join('/')}`;
      const existing = routes.get(urlPath);
      // Two route groups can serve the same URL; the agent file and the page may sit in either.
      routes.set(urlPath, {
        path: urlPath,
        page: page || Boolean(existing?.page),
        agentFile: agent ? path.join(dir, agent.name) : existing?.agentFile
      });
    }
    for (const entry of entries) {
      if (!entry.isDirectory() || skippedFolder(entry.name)) continue;
      walk(
        path.join(dir, entry.name),
        isRouteGroup(entry.name) ? urlSegments : [...urlSegments, entry.name]
      );
    }
  };

  walk(appDir, []);
  return [...routes.values()].sort((left, right) => left.path.localeCompare(right.path));
}

export const MANIFEST_DIR = '.netai';

export function renderManifest(routes: ScannedRoute[], manifestDir: string): string {
  const imports: string[] = [];
  const rows = routes.map((route) => {
    if (!route.agentFile) return `  { path: ${JSON.stringify(route.path)}, page: ${route.page} },`;
    const binding = `route${imports.length}`;
    const specifier = path
      .relative(manifestDir, route.agentFile)
      .split(path.sep)
      .join('/')
      .replace(/\.(tsx|ts|jsx|js)$/, '');
    imports.push(`import ${binding} from ${JSON.stringify(specifier.startsWith('.') ? specifier : `./${specifier}`)};`);
    return `  { path: ${JSON.stringify(route.path)}, page: ${route.page}, route: ${binding} },`;
  });
  return [
    '// Generated by @netai/next from your app/ folder. Do not edit; it is rewritten on every change.',
    "import type { RouteEntry } from '@netai/core';",
    ...imports,
    '',
    'export const manifest: RouteEntry[] = [',
    ...rows,
    '];',
    ''
  ].join('\n');
}

/** Writes `.netai/manifest.ts`, touching the file only when its content changed so dev reloads stay quiet. */
export function generateManifest(projectRoot: string): { file: string; routes: number; changed: boolean } {
  const appDir = findAppDir(projectRoot);
  if (!appDir) throw new Error(`[netai] no app/ or src/app/ folder under ${projectRoot}`);
  const manifestDir = path.join(projectRoot, MANIFEST_DIR);
  const file = path.join(manifestDir, 'manifest.ts');
  const routes = scanAppDir(appDir);
  const content = renderManifest(routes, manifestDir);
  const previous = existsSync(file) ? readFileSync(file, 'utf8') : undefined;
  if (previous === content) return { file, routes: routes.length, changed: false };
  mkdirSync(manifestDir, { recursive: true });
  writeFileSync(file, content);
  return { file, routes: routes.length, changed: true };
}
